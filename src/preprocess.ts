fs.writeFileSync(outputPath, `export const entry = sqliteTable('entry', {\n`, {flag: 'a'})
fs.writeFileSync(outputPath, `\tid: int().primaryKey(),\n`, {flag: 'a'})
fs.writeFileSync(outputPath, `})\n`, {flag: 'a'})
fs.writeFileSync(outputPath, `\n`, {flag: 'a'})

keyCount.keys().forEach((key: any) => {
  const parts = key.split(SEPARATOR)
  writeRootSchema(parts[parts.length-1])
})

