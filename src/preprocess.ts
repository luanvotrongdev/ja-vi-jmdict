import fs from 'fs'
import { exit } from 'process'
import {
  traverseJmdict,
} from "traverse"
import {
  getJmdict
} from "parser"

const SEPARATOR = '||'

let jmdict = await getJmdict()
if (!jmdict) {
  throw new Error("Failed to parse JMdict or it is not an array")
}

const keyCount: Map<string, number> = new Map<string, number>()
jmdict.entry.forEach((ele: any, index: number) => {
  keyCount.keys().forEach(key => {
    const current = keyCount.get(key) ?? 0
    keyCount.set(key, current < 2 ? 0 : current)
  });
  traverseJmdict(index, ["entry"], ele, (keyList, _) => {
    const key = keyList.join(SEPARATOR)
    const current = keyCount.get(key) ?? 0
    keyCount.set(key, current + 1)
  })
});

if (fs.existsSync(`${process.cwd()}/schemas`)) {
  fs.rmSync(`${process.cwd()}/schemas`, { recursive: true, force: true })
}
fs.mkdirSync(`${process.cwd()}/schemas`, { recursive: true })

const outputPath = `${process.cwd()}/schemas/index.ts`

