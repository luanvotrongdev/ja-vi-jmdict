fs.writeFileSync(outputPath, `import { int, sqliteTable } from 'drizzle-orm/sqlite-core'\n`, {flag: 'a'})
fs.writeFileSync(outputPath, `//\n`, {flag: 'a'})
fs.writeFileSync(outputPath, `//\n`, {flag: 'a'})
fs.writeFileSync(outputPath, `//\n`, {flag: 'a'})

